CREATE EXTENSION IF NOT EXISTS pg_trgm;  -- búsqueda de texto del catálogo (RF-11)

-- ---------------------------------------------------------------------
-- usuarios
-- ---------------------------------------------------------------------
CREATE TABLE usuarios (
    id_usuario             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombres                VARCHAR(100) NOT NULL,
    apellidos              VARCHAR(100) NOT NULL,
    correo_electronico     VARCHAR(150) NOT NULL,
    contrasena_hash        VARCHAR(255) NOT NULL,
    fecha_nacimiento       DATE,
    rol                    VARCHAR(20) NOT NULL,
    estado_cuenta          VARCHAR(20) NOT NULL DEFAULT 'Activo',
    correo_verificado      BOOLEAN NOT NULL DEFAULT false,
    fecha_registro         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_acceso          TIMESTAMPTZ,
    CONSTRAINT pk_usuarios PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuarios_correo_electronico UNIQUE (correo_electronico),
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('Administrador', 'Organizador', 'Participante')),
    CONSTRAINT ck_usuarios_estado_cuenta CHECK (estado_cuenta IN ('Activo', 'Inactivo', 'Pendiente')),
    CONSTRAINT ck_usuarios_correo_minusculas CHECK (correo_electronico = lower(correo_electronico))
);

-- ---------------------------------------------------------------------
-- categorias
-- ---------------------------------------------------------------------
CREATE TABLE categorias (
    id_categoria           SMALLINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre                 VARCHAR(60) NOT NULL,
    activa                 BOOLEAN NOT NULL DEFAULT true,
    fecha_creacion         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_categorias PRIMARY KEY (id_categoria),
    CONSTRAINT uq_categorias_nombre UNIQUE (nombre)
);

-- ---------------------------------------------------------------------
-- eventos
-- ---------------------------------------------------------------------
CREATE TABLE eventos (
    id_evento              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre_evento          VARCHAR(150) NOT NULL,
    descripcion            TEXT NOT NULL,
    id_categoria           SMALLINT NOT NULL,
    fecha_hora_inicio      TIMESTAMPTZ NOT NULL,
    fecha_hora_fin         TIMESTAMPTZ NOT NULL,
    fecha_limite_reserva   TIMESTAMPTZ NOT NULL,
    ubicacion              VARCHAR(200) NOT NULL,
    cupo_maximo            INTEGER NOT NULL,
    cupo_disponible        INTEGER NOT NULL,
    max_acompanantes       SMALLINT NOT NULL DEFAULT 0,
    precio                 NUMERIC(10,2) NOT NULL DEFAULT 0,
    imagen_url             VARCHAR(300),
    requiere_qr            BOOLEAN NOT NULL DEFAULT true,
    estado_evento          VARCHAR(20) NOT NULL DEFAULT 'Borrador',
    reprogramado           BOOLEAN NOT NULL DEFAULT false,
    motivo_cancelacion     VARCHAR(300),
    id_organizador         BIGINT NOT NULL,
    fecha_creacion         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_eventos PRIMARY KEY (id_evento),
    CONSTRAINT ck_eventos_fecha_hora_fin CHECK (fecha_hora_fin > fecha_hora_inicio),
    CONSTRAINT ck_eventos_fecha_limite_reserva CHECK (fecha_limite_reserva <= fecha_hora_inicio),
    CONSTRAINT ck_eventos_cupo_maximo CHECK (cupo_maximo > 0),
    CONSTRAINT ck_eventos_cupo_disponible CHECK (cupo_disponible BETWEEN 0 AND cupo_maximo),
    CONSTRAINT ck_eventos_max_acompanantes CHECK (max_acompanantes >= 0),
    CONSTRAINT ck_eventos_precio CHECK (precio >= 0),
    CONSTRAINT ck_eventos_estado_evento CHECK (estado_evento IN ('Borrador', 'Publicado', 'Cancelado', 'Finalizado')),
    CONSTRAINT ck_eventos_motivo_cancelacion CHECK (estado_evento <> 'Cancelado' OR motivo_cancelacion IS NOT NULL)
);

-- ---------------------------------------------------------------------
-- reservaciones
-- ---------------------------------------------------------------------
CREATE TABLE reservaciones (
    id_reservacion         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_evento              BIGINT NOT NULL,
    id_participante        BIGINT NOT NULL,
    cantidad_acompanantes  SMALLINT NOT NULL DEFAULT 0,
    observaciones          VARCHAR(300),
    monto                  NUMERIC(10,2) NOT NULL DEFAULT 0,
    codigo_comprobante     VARCHAR(64) NOT NULL,
    estado_reservacion     VARCHAR(20) NOT NULL DEFAULT 'Confirmada',
    fecha_reservacion      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_cancelacion      TIMESTAMPTZ,
    CONSTRAINT pk_reservaciones PRIMARY KEY (id_reservacion),
    CONSTRAINT uq_reservaciones_codigo_comprobante UNIQUE (codigo_comprobante),
    CONSTRAINT ck_reservaciones_cantidad_acompanantes CHECK (cantidad_acompanantes >= 0),
    CONSTRAINT ck_reservaciones_monto CHECK (monto >= 0),
    CONSTRAINT ck_reservaciones_estado_reservacion CHECK (estado_reservacion IN ('Confirmada', 'Cancelada')),
    CONSTRAINT ck_reservaciones_fecha_cancelacion CHECK (estado_reservacion <> 'Cancelada' OR fecha_cancelacion IS NOT NULL)
);

-- ---------------------------------------------------------------------
-- asistencias
-- ---------------------------------------------------------------------
CREATE TABLE asistencias (
    id_asistencia          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_reservacion         BIGINT NOT NULL,
    fecha_hora_validacion  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    metodo_validacion      VARCHAR(30) NOT NULL,
    id_registrado_por      BIGINT NOT NULL,
    anulada                BOOLEAN NOT NULL DEFAULT false,
    fecha_anulacion        TIMESTAMPTZ,
    id_anulada_por         BIGINT,
    CONSTRAINT pk_asistencias PRIMARY KEY (id_asistencia),
    CONSTRAINT ck_asistencias_metodo_validacion CHECK (metodo_validacion IN ('QR_Scanner', 'Manual_Organizador', 'Digital_Code')),
    CONSTRAINT ck_asistencias_anulacion CHECK ((anulada AND fecha_anulacion IS NOT NULL AND id_anulada_por IS NOT NULL) OR (NOT anulada AND fecha_anulacion IS NULL AND id_anulada_por IS NULL))
);

-- ---------------------------------------------------------------------
-- notificaciones
-- ---------------------------------------------------------------------
CREATE TABLE notificaciones (
    id_notificacion        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_usuario             BIGINT NOT NULL,
    id_evento              BIGINT,
    tipo_notificacion      VARCHAR(40) NOT NULL,
    asunto                 VARCHAR(150) NOT NULL,
    mensaje_contenido      TEXT NOT NULL,
    estado_envio           VARCHAR(15) NOT NULL DEFAULT 'Pendiente',
    intentos_envio         SMALLINT NOT NULL DEFAULT 0,
    leida                  BOOLEAN NOT NULL DEFAULT false,
    fecha_creacion         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_envio            TIMESTAMPTZ,
    CONSTRAINT pk_notificaciones PRIMARY KEY (id_notificacion),
    CONSTRAINT ck_notificaciones_tipo_notificacion CHECK (tipo_notificacion IN ('Bienvenida', 'Verificacion_Correo', 'Recuperacion_Contrasena', 'Aprobacion_Organizador', 'Rechazo_Organizador', 'Confirmacion_Reserva', 'Cancelacion_Reserva', 'Cambio_Evento', 'Cancelacion_Evento', 'Recordatorio')),
    CONSTRAINT ck_notificaciones_estado_envio CHECK (estado_envio IN ('Pendiente', 'Enviado', 'Fallido'))
);

-- ---------------------------------------------------------------------
-- tokens_usuario
-- ---------------------------------------------------------------------
CREATE TABLE tokens_usuario (
    id_token               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_usuario             BIGINT NOT NULL,
    tipo                   VARCHAR(30) NOT NULL,
    token_hash             VARCHAR(255) NOT NULL,
    fecha_expiracion       TIMESTAMPTZ NOT NULL,
    usado                  BOOLEAN NOT NULL DEFAULT false,
    intentos               SMALLINT NOT NULL DEFAULT 0,
    fecha_creacion         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    correo_nuevo           VARCHAR(150),
    CONSTRAINT pk_tokens_usuario PRIMARY KEY (id_token),
    CONSTRAINT ck_tokens_usuario_tipo CHECK (tipo IN ('Verificacion_Correo', 'Recuperacion_Contrasena', 'Refresh', 'Cambio_Correo')),
    CONSTRAINT ck_tokens_usuario_intentos CHECK (intentos BETWEEN 0 AND 5),
    CONSTRAINT ck_tokens_usuario_correo_nuevo CHECK (tipo <> 'Cambio_Correo' OR correo_nuevo IS NOT NULL),
    CONSTRAINT ck_tokens_usuario_correo_nuevo_minusculas CHECK (correo_nuevo = lower(correo_nuevo))
);

-- ---------------------------------------------------------------------
-- bitacora
-- ---------------------------------------------------------------------
CREATE TABLE bitacora (
    id_bitacora            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_usuario             BIGINT,
    accion                 VARCHAR(60) NOT NULL,
    entidad                VARCHAR(40),
    id_entidad             BIGINT,
    detalle                JSONB,
    ip                     VARCHAR(45),
    fecha                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_bitacora PRIMARY KEY (id_bitacora)
);

-- ---------------------------------------------------------------------
-- solicitudes_soporte
-- ---------------------------------------------------------------------
CREATE TABLE solicitudes_soporte (
    id_solicitud           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_usuario             BIGINT,
    correo_contacto        VARCHAR(150) NOT NULL,
    tipo                   VARCHAR(30) NOT NULL,
    descripcion            TEXT NOT NULL,
    estado                 VARCHAR(20) NOT NULL DEFAULT 'Abierta',
    fecha_creacion         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_solicitudes_soporte PRIMARY KEY (id_solicitud),
    CONSTRAINT ck_solicitudes_soporte_tipo CHECK (tipo IN ('Incidente', 'Solicitud_Cambio', 'Consulta', 'Acceso')),
    CONSTRAINT ck_solicitudes_soporte_estado CHECK (estado IN ('Abierta', 'En_Proceso', 'Cerrada'))
);

